/**
 * @typedef {{ id: string, type: string, inventoriType: string, contentType: string|null, sha256: string|null, sizeBytes: number|null, createdAt: string|null }} ArtifactListItem
 * @typedef {{ contentType: string, contentDisposition: string, bytes: Buffer }} ArtifactProxyResult
 */

/**
 * Lists Billing fiscal artifacts through Inventori's ownership boundary.
 *
 * @param {bigint} invoiceId Inventori Invoice ID
 * @param {bigint} companyId Authenticated Inventori company ID
 * @param {{ billingClient?: object, db?: object, correlationId?: string }} [options]
 * @returns {Promise<ArtifactListItem[]>}
 */
async function listFiscalArtifacts(invoiceId, companyId, options = {}) {
  const db = options.db || prisma;
  const { intent, config } = await resolveArtifactOwnershipChain(invoiceId, companyId, db);
  const correlationId = options.correlationId
    || `inventori-artifact-list-${String(intent.id)}-${Date.now()}`;

  const billingClient = options.billingClient || new BillingApiClient({
    baseUrl: config.baseUrl || process.env.BILLING_BASE_URL || 'http://localhost:4000',
    credentialResolver: createBillingCredentialResolver(),
    timeoutMs: Number(process.env.BILLING_ARTIFACT_TIMEOUT_MS) || 30000,
  });

  let artifacts;
  try {
    artifacts = await billingClient.listArtifacts({
      billingCompanyId: config.billingCompanyId,
      environment: String(config.billingEnvironment).toUpperCase(),
      billingFiscalDocumentId: intent.billingFiscalDocumentId,
      secretReference: config.billingCredentialSecretRef,
      correlationId,
    });
  } catch (error) {
    throw mapArtifactBillingErrorToHttp(error);
  }

  const billingToInventori = Object.entries(INVENTORI_TO_BILLING_ARTIFACT_TYPE)
    .reduce((acc, [inventoriType, billingType]) => ({ ...acc, [billingType]: inventoriType }), {});

  return artifacts
    .filter((artifact) => billingToInventori[artifact.type])
    .map((artifact) => ({
      id: artifact.id,
      type: artifact.type,
      inventoriType: billingToInventori[artifact.type],
      contentType: artifact.contentType || ARTIFACT_MIME_BY_BILLING_TYPE[artifact.type] || null,
      sha256: artifact.sha256 || null,
      sizeBytes: artifact.sizeBytes == null ? null : Number(artifact.sizeBytes),
      createdAt: artifact.createdAt || null,
    }));
}

/**
 * Retrieves a Billing fiscal artifact and returns it for proxy delivery to the caller.
 *
 * INVARIANTS (all enforced by this function):
 * - Never mutates any Inventori DB record.
 * - Never persists artifact bytes.
 * - Never exposes Billing API key in result, logs, or errors.
 * - Never contacts Hacienda directly.
 * - Artifact type validated before any DB or network call.
 * - Ownership resolved before any Billing request.
 * - All error paths return safe HTTP errors without Billing internals.
 *
 * @param {bigint} invoiceId Inventori Invoice ID
 * @param {string} inventoriArtifactType URL-safe type: 'pdf' | 'signed-xml' | 'hacienda-response'
 * @param {bigint} companyId Authenticated Inventori company ID
 * @param {{ billingClient?: object, db?: object, correlationId?: string, maxBytes?: number }} [options]
 * @returns {Promise<ArtifactProxyResult>}
 */
async function getFiscalArtifact(invoiceId, inventoriArtifactType, companyId, options = {}) {
  // 1. Validate artifact type BEFORE any DB or network call
  const billingArtifactType = INVENTORI_TO_BILLING_ARTIFACT_TYPE[inventoriArtifactType];
  if (!billingArtifactType) {
    const valid = Object.keys(INVENTORI_TO_BILLING_ARTIFACT_TYPE).join(', ');
    throw createHttpError(
      400,
      `Tipo de artefacto no soportado: '${String(inventoriArtifactType).slice(0, 60)}'. Tipos válidos: ${valid}`,
      'ARTIFACT_TYPE_UNSUPPORTED',
    );
  }

  // 2. Resolve ownership chain: company → invoice → intent → config
  const db = options.db || prisma;
  const { intent, config } = await resolveArtifactOwnershipChain(invoiceId, companyId, db);

  const correlationId = options.correlationId
    || `inventori-artifact-${String(intent.id)}-${Date.now()}`;

  logArtifactEvent('info', {
    companyId,
    invoiceId,
    fiscalIntentId: intent.id,
    billingFiscalDocumentId: intent.billingFiscalDocumentId,
    artifactType: billingArtifactType,
    correlationId,
    result: 'REQUEST_START',
  });

  // 3. Build Billing client (or use injected client for testing)
  const billingClient = options.billingClient || new BillingApiClient({
    baseUrl: config.baseUrl || process.env.BILLING_BASE_URL || 'http://localhost:4000',
    credentialResolver: createBillingCredentialResolver(),
    timeoutMs: Number(process.env.BILLING_ARTIFACT_TIMEOUT_MS) || 30000,
  });

  const maxBytes = options.maxBytes != null ? options.maxBytes : DEFAULT_ARTIFACT_MAX_BYTES;

  // 4. Call Billing — resolve secretReference from config (not from caller)
  let artifactResult;
  try {
    artifactResult = await billingClient.getArtifact({
      billingCompanyId: config.billingCompanyId,
      environment: String(config.billingEnvironment).toUpperCase(),
      billingFiscalDocumentId: intent.billingFiscalDocumentId,
      artifactType: billingArtifactType,
      secretReference: config.billingCredentialSecretRef,
      correlationId,
      maxBytes,
    });
  } catch (error) {
    const httpError = mapArtifactBillingErrorToHttp(error);
    logArtifactEvent('warn', {
      companyId,
      invoiceId,
      fiscalIntentId: intent.id,
      billingFiscalDocumentId: intent.billingFiscalDocumentId,
      artifactType: billingArtifactType,
      correlationId,
      result: 'REQUEST_FAILED',
      errorCode: httpError.code,
    });
    throw httpError;
  }

  logArtifactEvent('info', {
    companyId,
    invoiceId,
    fiscalIntentId: intent.id,
    billingFiscalDocumentId: intent.billingFiscalDocumentId,
    artifactType: billingArtifactType,
    correlationId,
    result: 'REQUEST_OK',
    byteCount: artifactResult.bytes.length,
  });

  // 5. Generate safe Content-Disposition (never copy from Billing)
  const contentDisposition = buildContentDisposition(billingArtifactType, intent.clave, invoiceId);

  // 6. Return proxy result — no bytes persisted beyond this call
  return {
    contentType: artifactResult.contentType,
    contentDisposition,
    bytes: artifactResult.bytes,
  };
}

