'use strict';

/**
 * TASK-014 — Billing fiscal artifact proxy service.
 *
 * Proxies Billing-owned fiscal artifacts (PDF, signed XML, Hacienda response XML)
 * through Inventori's ownership/authorization boundary.
 *
 * CRITICAL INVARIANTS:
 * ─────────────────────────────────────────────────────────────────────────────
 * 1. READ-ONLY: Artifact retrieval NEVER mutates Invoice.status,
 *    InvoiceFiscalIntent.status, clave, consecutive, or idempotencyKey.
 * 2. OWNERSHIP: The caller can never substitute another company's Billing IDs.
 *    Resolution chain: auth.companyId → Invoice → InvoiceFiscalIntent → Config.
 * 3. SECRET SAFETY: Billing API key is used ONLY in the outbound X-API-Key header.
 *    It is never returned, logged, stored, or included in error responses.
 * 4. NO DUPLICATION: Artifact bytes are NEVER persisted in any Inventori table.
 * 5. SAFE HEADERS: Only Content-Type, Content-Disposition, Content-Length are
 *    set on the Inventori response. No upstream Billing headers are forwarded.
 * 6. SAFE FILENAME: Content-Disposition is generated by Inventori, never copied
 *    from Billing. Clave values are sanitized to prevent path traversal / CRLF.
 * 7. BILLING IS AUTHORITATIVE: Inventori never generates fiscal PDF/XML itself.
 * 8. NO DIRECT HACIENDA: This service never contacts Hacienda endpoints.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Billing artifact endpoint (official Billing contract):
 *   GET /api/v1/companies/{billingCompanyId}/fiscal-documents/{env}/invoices/{docId}/artifacts
 *   GET /api/v1/companies/{billingCompanyId}/fiscal-documents/{env}/invoices/{docId}/artifacts/{artifactId}/download
 *
 * Inventori proxy endpoint:
 *   GET /api/invoices/:invoiceId/fiscal-artifacts/:artifactType
 *
 * Supported artifact types (Inventori URL → Billing canonical):
 *   pdf              → PDF               → application/pdf
 *   signed-xml       → SIGNED_XML        → application/xml
 *   hacienda-response → HACIENDA_RESPONSE_XML → application/xml
 */

const prisma = require('../lib/prisma');
const { BillingApiClient, BillingClientError, DEFAULT_ARTIFACT_MAX_BYTES } = require('./billing-api-client.service');
const { createBillingCredentialResolver } = require('./billing-credential-resolver.service');
const { createHttpError } = require('../lib/errors');

// ---------------------------------------------------------------------------
// P0 Artifact type mapping
// ---------------------------------------------------------------------------

/**
 * Maps Inventori URL-safe artifact type to Billing canonical type.
 * Only entries in this map are supported. Any unknown type is hard-blocked
 * BEFORE any Billing network call.
 *
 * @type {Readonly<Record<string, string>>}
 */
const INVENTORI_TO_BILLING_ARTIFACT_TYPE = Object.freeze({
  'pdf': 'PDF',
  'signed-xml': 'SIGNED_XML',
  'hacienda-response': 'HACIENDA_RESPONSE_XML',
});

/**
 * Expected MIME type for each Billing canonical artifact type.
 * @type {Readonly<Record<string, string>>}
 */
const ARTIFACT_MIME_BY_BILLING_TYPE = Object.freeze({
  PDF: 'application/pdf',
  SIGNED_XML: 'application/xml',
  HACIENDA_RESPONSE_XML: 'application/xml',
});

/**
 * Safe file extension by Billing canonical type.
 * @type {Readonly<Record<string, string>>}
 */
const ARTIFACT_EXTENSION_BY_BILLING_TYPE = Object.freeze({
  PDF: 'pdf',
  SIGNED_XML: 'xml',
  HACIENDA_RESPONSE_XML: 'xml',
});

/**
 * Filename prefix by Billing canonical type.
 * @type {Readonly<Record<string, string>>}
 */
const ARTIFACT_FILENAME_PREFIX_BY_BILLING_TYPE = Object.freeze({
  PDF: 'factura',
  SIGNED_XML: 'factura',
  HACIENDA_RESPONSE_XML: 'respuesta-hacienda',
});

// ---------------------------------------------------------------------------
// Safe Content-Disposition generation
// ---------------------------------------------------------------------------

/**
 * Builds a deterministic safe Content-Disposition: attachment header value.
 *
 * Safety guarantees:
 * - Clave is sanitized to [a-zA-Z0-9] only, max 50 chars.
 * - InvoiceId is sanitized to digits only.
 * - CRLF and control characters are detected and replaced with a safe fallback.
 * - Never copies or forwards an upstream Billing Content-Disposition header.
 * - Result is always in the form: `attachment; filename="<safe-name>.<ext>"`
 *
 * @param {string} billingArtifactType Billing canonical type (PDF / SIGNED_XML / HACIENDA_RESPONSE_XML)
 * @param {string|null} clave InvoiceFiscalIntent.clave from DB (may be null pre-acceptance)
 * @param {bigint|string|number} invoiceId Inventori invoice ID for fallback identifier
 * @returns {string} Safe Content-Disposition header value
 */
function buildContentDisposition(billingArtifactType, clave, invoiceId) {
  const prefix = ARTIFACT_FILENAME_PREFIX_BY_BILLING_TYPE[billingArtifactType] || 'fiscal';
  const ext = ARTIFACT_EXTENSION_BY_BILLING_TYPE[billingArtifactType] || 'bin';

  let safePart;
  if (clave && typeof clave === 'string' && clave.trim().length > 0) {
    // Clave in production is numeric only; sanitize defensively against any injection
    const sanitized = clave.replace(/[^a-zA-Z0-9]/g, '').slice(0, 50);
    if (sanitized.length > 0) {
      safePart = sanitized;
    }
  }

  if (!safePart) {
    const safeId = String(invoiceId || '').replace(/[^0-9]/g, '').slice(0, 20) || 'unknown';
    safePart = `inv-${safeId}`;
  }

  const filename = `${prefix}-${safePart}.${ext}`;

  // Final guard: reject any CRLF, null bytes or control characters
  // eslint-disable-next-line no-control-regex
  if (/[\r\n\x00-\x1f\x7f]/.test(filename)) {
    return `attachment; filename="${prefix}-safe.${ext}"`;
  }

  return `attachment; filename="${filename}"`;
}

// ---------------------------------------------------------------------------
// Billing artifact error → Inventori HTTP error mapping
// ---------------------------------------------------------------------------

/**
 * Maps a BillingClientError from artifact retrieval to a safe HTTP error.
 *
 * CRITICAL: this function MUST NOT change InvoiceFiscalIntent or Invoice.
 * All error paths are read-only.
 *
 * @param {Error} error
 * @returns {Error & { statusCode: number, code: string }}
 */
function mapArtifactBillingErrorToHttp(error) {
  if (!(error instanceof BillingClientError)) {
    // Non-Billing errors: generic 502 without leaking internal details
    return createHttpError(502, 'Error al obtener artefacto fiscal', 'BILLING_ARTIFACT_UNAVAILABLE');
  }

  const { code, statusCode } = error;

  switch (code) {
    case 'BILLING_TIMEOUT':
      return createHttpError(504, 'Tiempo de espera agotado al obtener artefacto fiscal', 'BILLING_TIMEOUT');
    case 'BILLING_UNAVAILABLE':
      return createHttpError(503, 'Servicio de facturación no disponible temporalmente', 'BILLING_UNAVAILABLE');
    case 'BILLING_ARTIFACT_TOO_LARGE':
      return createHttpError(502, 'Artefacto fiscal excede el tamaño máximo permitido', 'BILLING_ARTIFACT_TOO_LARGE');
    case 'BILLING_UNEXPECTED_CONTENT_TYPE':
      return createHttpError(502, 'Tipo de contenido inesperado del artefacto fiscal', 'BILLING_ARTIFACT_CONTENT_TYPE_ERROR');
    default:
      break;
  }

  // HTTP status-based mapping for pass-through Billing errors
  if (statusCode === 404) {
    return createHttpError(404, 'Artefacto fiscal no encontrado en Billing', 'FISCAL_ARTIFACT_NOT_FOUND');
  }
  if (statusCode === 401 || statusCode === 403) {
    // Do not expose auth details — return 502 to hide credential configuration
    return createHttpError(502, 'Error de autenticación con el sistema de facturación', 'BILLING_ARTIFACT_AUTH_ERROR');
  }
  if (statusCode === 429 || statusCode === 503) {
    return createHttpError(503, 'Servicio de facturación no disponible temporalmente', 'BILLING_UNAVAILABLE');
  }
  if (statusCode && statusCode >= 400 && statusCode < 500) {
    return createHttpError(422, 'El sistema de facturación rechazó la solicitud de artefacto', 'BILLING_ARTIFACT_INVALID_REQUEST');
  }

  return createHttpError(502, 'Error al obtener artefacto fiscal de Billing', 'BILLING_ARTIFACT_ERROR');
}

// ---------------------------------------------------------------------------
// Ownership resolution
// ---------------------------------------------------------------------------

/**
 * Resolves the complete artifact access chain from the authenticated company scope.
 *
 * Chain: companyId → Invoice → InvoiceFiscalIntent → CompanyBillingIntegrationConfig
 *
 * Failure semantics use not-found (404) for cross-company access per Inventori security
 * convention — callers cannot distinguish between "not found" and "not yours".
 *
 * @param {bigint} invoiceId
 * @param {bigint} companyId
 * @param {object} [db]
 * @returns {Promise<{ invoice: object, intent: object, config: object }>}
 */
async function resolveArtifactOwnershipChain(invoiceId, companyId, db = prisma) {
  // Invoice must belong to the authenticated company (via client.companyId)
  const invoice = await /** @type {any} */ (db).invoice.findFirst({
    where: { id: invoiceId, client: { companyId } },
    select: { id: true, status: true },
  });
  if (!invoice) {
    throw createHttpError(404, 'Factura no encontrada', 'not_found');
  }

  // Fiscal intent must exist
  const intent = await /** @type {any} */ (db).invoiceFiscalIntent.findUnique({
    where: { invoiceId },
    include: { integrationConfig: true },
  });
  if (!intent) {
    throw createHttpError(422, 'Esta factura no tiene proceso de emisión fiscal iniciado', 'FISCAL_INTENT_NOT_FOUND');
  }

  // Billing fiscal document must have been created (no document → artifact not possible)
  if (!intent.billingFiscalDocumentId) {
    throw createHttpError(422, 'El documento fiscal aún no ha sido enviado a Billing; el artefacto no está disponible', 'ARTIFACT_NOT_READY');
  }

  // Defensive: intent.companyId must match authenticated company
  // (Should be guaranteed by invoice scope, but defence in depth)
  if (intent.companyId.toString() !== companyId.toString()) {
    throw createHttpError(403, 'Acceso denegado', 'forbidden');
  }

  const config = intent.integrationConfig;
  if (!config) {
    throw createHttpError(503, 'Configuración de integración Billing no encontrada', 'BILLING_CONFIG_MISSING');
  }

  return { invoice, intent, config };
}

// ---------------------------------------------------------------------------
// Safe structured logging
// ---------------------------------------------------------------------------

/**
 * Logs artifact access events. Only safe fields — never logs artifact bytes,
 * API key, XML content, receiver PII, or credential references.
 *
 * @param {'info'|'warn'|'error'} level
 * @param {object} event
 */
function logArtifactEvent(level, event) {
  const payload = {
    level,
    component: 'fiscal-artifact-proxy',
    companyId: event.companyId != null ? String(event.companyId) : null,
    invoiceId: event.invoiceId != null ? String(event.invoiceId) : null,
    fiscalIntentId: event.fiscalIntentId != null ? String(event.fiscalIntentId) : null,
    billingFiscalDocumentId: event.billingFiscalDocumentId || null,
    artifactType: event.artifactType || null,
    correlationId: event.correlationId || null,
    result: event.result || null,
    byteCount: event.byteCount != null ? Number(event.byteCount) : null,
    errorCode: event.errorCode || null,
  };
  const logFn = level === 'error' ? console.error : level === 'warn' ? console.warn : console.info;
  logFn(JSON.stringify(payload));
}

